"""Generate the frontend's API types from the OpenAPI schema.

`openapi-typescript` builds its output with the TypeScript compiler API,
which TypeScript 7 no longer ships, so the schema is walked here. It is
a small, closed shape: objects, arrays, refs, unions and string enums.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from app.main import app

HEADER = "// Generated by `make types`. Do not edit.\n"


def main() -> None:
    target = Path(sys.argv[1] if len(sys.argv) > 1 else "api-types.ts")
    schemas = app.openapi()["components"]["schemas"]
    blocks = [HEADER]
    blocks.extend(
        _declaration(name, schemas[name]) for name in sorted(schemas)
    )
    target.write_text("\n".join(blocks))
    print(f"wrote {target}")


def _declaration(name: str, schema: dict[str, Any]) -> str:
    if schema.get("type") != "object" and "properties" not in schema:
        return f"export type {name} = {_type(schema, 0)}\n"

    lines = [f"export interface {name} {{"]
    required = set(schema.get("required", ()))
    for field, value in schema.get("properties", {}).items():
        optional = "" if field in required else "?"
        lines.append(f"  {field}{optional}: {_type(value, 1)}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _type(schema: dict[str, Any], depth: int) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(_type(part, depth) for part in schema["anyOf"])

    kind = schema.get("type")
    if kind == "array":
        item = _type(schema["items"], depth)
        return f"({item})[]" if "|" in item else f"{item}[]"
    if kind == "object":
        return _object(schema, depth)
    if kind == "string":
        return _enum(schema) or "string"
    if kind in {"integer", "number"}:
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    return "unknown"


def _object(schema: dict[str, Any], depth: int) -> str:
    properties = schema.get("properties")
    if properties:
        pad = "  " * (depth + 1)
        required = set(schema.get("required", ()))
        lines = ["{"]
        for field, value in properties.items():
            optional = "" if field in required else "?"
            lines.append(f"{pad}{field}{optional}: {_type(value, depth + 1)}")
        lines.append("  " * depth + "}")
        return "\n".join(lines)

    extra = schema.get("additionalProperties")
    if isinstance(extra, dict):
        return f"Record<string, {_type(extra, depth)}>"
    return "Record<string, unknown>"


def _enum(schema: dict[str, Any]) -> str:
    values = schema.get("enum")
    if not values:
        return ""
    return " | ".join(json.dumps(value) for value in values)


if __name__ == "__main__":
    main()
